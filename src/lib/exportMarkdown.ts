import { AnalysisResult } from "@/types";

export function generateFullAuditMarkdown(analysis: AnalysisResult): string {
  const dateStr = new Date(analysis.timestamp).toLocaleString();
  const scope = analysis.userScope;

  return `# BlindspotIQ Decision Verification & Gap Audit Report
Generated: ${dateStr}

---

## 1. Research Objective & Context
- **Research Goal:** ${analysis.topic}
- **Detected Domain:** ${analysis.detectedCategory}
- **Overall Completeness Score:** ${analysis.overallCompletenessScore}%
- **High-Risk Dark Spots:** ${analysis.highRiskCount}
${
  scope
    ? `
### Applicant Context & Scope:
- **Situation / Profile:** ${scope.situation || "Unspecified"}
- **Jurisdiction / Region:** ${scope.jurisdiction || "Unspecified"}
- **Target Cycle:** ${scope.targetCycle || "Unspecified"}
`
    : ""
}

---

## 2. Executive Synthesis & Domain Verdict
${analysis.executiveSummary}

- **Primary Official Portal:** ${analysis.officialApplicationUrl || "Not verified"}
- **Official Gateway Title:** ${analysis.officialApplicationTitle || "Primary Authority Gateway"}

---

## 3. Confirmed Key Facts (Across Evaluated Sources)
${
  analysis.confirmedFacts.length === 0
    ? "_No fully confirmed facts extracted._"
    : analysis.confirmedFacts
        .map(
          (f, i) => `### 3.${i + 1} ${f.dimensionName}
- **Confirmed Fact:** ${f.fact}
- **Source Authority:** ${f.sourceTitle} (Weight: ${f.authorityWeight}%)
${f.verifiedQuote ? `- **Direct Quoted Citation:** _"${f.verifiedQuote}"_` : ""}`
        )
        .join("\n\n")
}

---

## 4. Critical Information Gaps (Dark Spots)
${
  analysis.gaps.length === 0
    ? "_No critical information gaps identified._"
    : analysis.gaps
        .map(
          (g, i) => `### 4.${i + 1} ${g.dimensionName} [Risk: ${g.riskLevel.toUpperCase()}${g.gapType ? ` | Type: ${g.gapType.replace(/_/g, " ").toUpperCase()}` : ""}]
- **Gap Description:** ${g.description}
- **Impact / Vulnerability:** ${g.impactReason}
- **Recommended Action:** ${g.actionRequired}`
        )
        .join("\n\n")
}

---

## 5. Cross-Source Contradictions & Clashes
${
  analysis.contradictions.length === 0
    ? "_No direct factual clashes detected among ingested sources._"
    : analysis.contradictions
        .map(
          (c, i) => `### 5.${i + 1} Contested: ${c.dimensionName} [Severity: ${c.severity.toUpperCase()}${c.conflictType ? ` | Type: ${c.conflictType.replace(/_/g, " ").toUpperCase()}` : ""}]
- **Claim A (${c.claimA.sourceTitle} - ${c.claimA.authorityTier}, Weight ${c.claimA.authorityWeight}%):**
  - Statement: ${c.claimA.statement}
  - Quoted Text: _"${c.claimA.quote}"_
- **Claim B (${c.claimB.sourceTitle} - ${c.claimB.authorityTier}, Weight ${c.claimB.authorityWeight}%):**
  - Statement: ${c.claimB.statement}
  - Quoted Text: _"${c.claimB.quote}"_
- **Authority-Weighted Verdict:**
  - Preferred Claim: ${c.authorityVerdict.preferredClaim.toUpperCase()}
  - Rationale: ${c.authorityVerdict.rationale}
- **Why It Matters:** ${c.whyItMatters}
- **Resolution Recommendation:** ${c.recommendation}`
        )
        .join("\n\n")
}

---

## 6. Freshness & Temporal Alerts
${
  analysis.temporalAlerts.length === 0
    ? "_All ingested sources appear current or cycle-aligned._"
    : analysis.temporalAlerts
        .map(
          (t, i) => `### 6.${i + 1} ${t.sourceTitle} [${t.severity.toUpperCase()}]
- **Warning:** ${t.warningMessage}
- **Detected Cycle:** ${t.detectedCycleOrYear || "Undated"} (Current: ${t.currentCycleOrYear})`
        )
        .join("\n\n")
}

---

## 7. Action Verification Checklist
${
  analysis.verificationChecklist.length === 0
    ? "_Checklist empty._"
    : analysis.verificationChecklist
        .map(
          (item) =>
            `- [${item.completed ? "x" : " "}] **[${item.priority.toUpperCase()}]** ${item.task}${item.isUserAdded ? " *(User Added)*" : ""}
  - *Reason:* ${item.reason}
  - *Target Authority:* ${item.recommendedOfficialSource || "Primary institution office"}
  - *Search Shortcut:* \`${item.searchQueryShortcut || item.task}\``
        )
        .join("\n\n")
}

---

## 8. Ingested Sources & Authority Tiering
${analysis.sources
  .map(
    (s, i) => `### 8.${i + 1} ${s.title}
- **URL / Location:** ${s.url}
- **Domain:** ${s.hostname}
- **Authority Tier:** ${s.authorityTier} (${s.authorityWeight}% weight)
- **Rationale:** ${s.authorityRationale}
- **Cycle / Date:** ${s.cycleOrYear || s.publishDate || "Undated"}`
  )
  .join("\n\n")}

---

### Responsible AI & Legal Disclaimer
_This audit was generated by BlindspotIQ for informational and decision-verification purposes. AI-suggested signals and detected dark spots represent potential inquiry items derived from reviewed text, not guaranteed legal or statutory rulings. Always verify critical requirements directly with the issuing department._
`;
}
